-- ---------- 6. Order functions (service-role only) ----------
create or replace function public.create_order(
  p_user uuid, p_customer jsonb, p_items jsonb, p_method text, p_key text,
  p_shipping_flat numeric default 0, p_free_above numeric default null
) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  v_existing public.orders;
  v_agg record;
  v_item jsonb;
  v_prod public.products;
  v_var public.product_variants;
  v_vcount int;
  v_vid bigint;
  v_qty int; v_size text; v_unit numeric; v_pack int; v_pieces int;
  v_label text; v_sku text;
  v_cat text;
  v_lines jsonb := '[]'::jsonb;
  v_sub numeric := 0; v_ship numeric := 0;
  v_order public.orders; v_number text;
begin
  if p_user is null then raise exception 'LOGIN_REQUIRED'; end if;
  if p_method not in ('COD','ONLINE') then raise exception 'INVALID_METHOD'; end if;
  if p_items is null or jsonb_typeof(p_items) <> 'array'
     or jsonb_array_length(p_items) < 1 or jsonb_array_length(p_items) > 20 then
    raise exception 'INVALID_ITEMS';
  end if;

  if p_key is not null then
    select * into v_existing from public.orders where user_id = p_user and idempotency_key = p_key;
    if found then return jsonb_build_object('existing', true, 'order', to_jsonb(v_existing)); end if;
  end if;

  -- Pass 1: lock each product (ordered by id = no deadlocks), check it is sellable and the minimum order quantity.
  for v_agg in
    select (e->>'productId')::bigint as pid, sum((e->>'qty')::int) as qty
    from jsonb_array_elements(p_items) as t(e) group by 1 order by 1
  loop
    select * into v_prod from public.products where id = v_agg.pid for update;
    if not found or not v_prod.active or v_prod.archived then raise exception 'UNAVAILABLE'; end if;
    v_cat := case when v_prod.category in ('mala', 'necklace') then 'mala-and-necklace' else v_prod.category end;
    if exists (select 1 from public.categories) and not exists (select 1 from public.categories c where c.slug = v_cat and c.active) then
      raise exception 'UNAVAILABLE';
    end if;
    if v_agg.qty < coalesce(v_prod.min_order_qty, 1) then
      raise exception 'MIN_QTY:%:%', v_prod.name, coalesce(v_prod.min_order_qty, 1);
    end if;
  end loop;

  -- Pass 2: price every line from the database and take stock (in individual pieces) atomically.
  for v_item in
    select value from jsonb_array_elements(p_items)
    order by (value->>'productId')::bigint, coalesce(nullif(value->>'variantId', '')::bigint, 0)
  loop
    select * into v_prod from public.products where id = (v_item->>'productId')::bigint;
    v_qty  := (v_item->>'qty')::int;
    v_size := nullif(trim(coalesce(v_item->>'size', '')), '');
    v_vid  := nullif(v_item->>'variantId', '')::bigint;
    if v_qty is null or v_qty < 1 or v_qty > 99 then raise exception 'INVALID_ITEMS'; end if;

    select count(*) into v_vcount from public.product_variants where product_id = v_prod.id and active;
    if v_vcount > 0 then
      if v_vid is null then raise exception 'VARIANT_REQUIRED:%', v_prod.name; end if;
      select * into v_var from public.product_variants where id = v_vid and product_id = v_prod.id and active for update;
      if not found then raise exception 'UNAVAILABLE'; end if;
      v_pack   := greatest(coalesce(v_var.pack_qty, 1), 1);
      v_unit   := case when v_var.sale_price is not null and v_var.sale_price > 0 and v_var.sale_price < v_var.price then v_var.sale_price else v_var.price end;
      v_pieces := v_qty * v_pack;
      update public.product_variants set stock = stock - v_pieces, updated_at = now() where id = v_var.id and stock >= v_pieces;
      if not found then raise exception 'OUT_OF_STOCK:%', v_prod.name || ' (' || v_var.label || ')'; end if;
      v_label := v_var.label; v_sku := coalesce(nullif(v_var.sku, ''), v_prod.sku); v_size := null;
    else
      if coalesce(array_length(v_prod.sizes, 1), 0) > 0 then
        if v_size is null or not (v_size = any (v_prod.sizes)) then raise exception 'SIZE_REQUIRED:%', v_prod.name; end if;
      else
        v_size := null;
      end if;
      v_vid    := null;
      v_pack   := greatest(coalesce(v_prod.pack_size, 1), 1);
      v_unit   := case when v_prod.sale_price is not null and v_prod.sale_price > 0 and v_prod.sale_price < v_prod.price then v_prod.sale_price else v_prod.price end;
      v_pieces := v_qty * v_pack;
      update public.products set stock = stock - v_pieces where id = v_prod.id and stock >= v_pieces;
      if not found then raise exception 'OUT_OF_STOCK:%', v_prod.name; end if;
      v_label := null; v_sku := v_prod.sku;
    end if;

    v_sub := v_sub + v_unit * v_qty;
    v_lines := v_lines || jsonb_build_object(
      'product_id', v_prod.id, 'variant_id', v_vid, 'name', v_prod.name, 'slug', v_prod.slug,
      'variant_label', v_label, 'sku', v_sku, 'size', v_size, 'qty', v_qty, 'pack_qty', v_pack,
      'unit_price', v_unit, 'image', v_prod.image_urls[1],
      'return_policy', jsonb_build_object(
        'eligible', v_prod.return_eligible, 'window_days', v_prod.return_window_days,
        'conditions', v_prod.return_conditions, 'instructions', v_prod.return_instructions,
        'refund_policy', v_prod.refund_policy));
  end loop;

  v_ship := public.delivery_charge(v_sub);
  v_number := 'SJC-' || to_char(now() at time zone 'Asia/Kolkata', 'YYMMDD') || '-'
              || upper(substr(md5(random()::text || clock_timestamp()::text), 1, 5));

  insert into public.orders(order_number, user_id, customer_name, phone, email, address, city, state, pincode,
                            payment_method, payment_status, order_status, items, subtotal, shipping, total, idempotency_key)
  values (v_number, p_user, p_customer->>'name', p_customer->>'phone', nullif(p_customer->>'email', ''),
          p_customer->>'address', p_customer->>'city', p_customer->>'state', p_customer->>'pincode',
          p_method, 'pending', 'pending', v_lines, v_sub, v_ship, v_sub + v_ship, p_key)
  returning * into v_order;

  insert into public.order_events(order_id, event_type, to_status, note, actor, actor_id)
  values (v_order.id, 'placed', 'pending', 'Order placed', 'customer', p_user);

  return jsonb_build_object('existing', false, 'order', to_jsonb(v_order));
end $$;

-- Gives reserved stock back exactly once. Stock is counted in pieces: qty x pack_qty.
create or replace function public.restore_order_stock(p_order bigint) returns void
language plpgsql security definer set search_path = public as $$
declare v_o public.orders; v_i jsonb; v_pieces int;
begin
  select * into v_o from public.orders where id = p_order for update;
  if not found or v_o.stock_restored then return; end if;
  for v_i in select value from jsonb_array_elements(v_o.items) loop
    v_pieces := coalesce((v_i->>'qty')::int, 0) * greatest(coalesce((v_i->>'pack_qty')::int, 1), 1);
    if nullif(v_i->>'variant_id', '') is not null then
      update public.product_variants set stock = stock + v_pieces, updated_at = now() where id = (v_i->>'variant_id')::bigint;
    else
      update public.products set stock = stock + v_pieces where id = (v_i->>'product_id')::bigint;
    end if;
  end loop;
  update public.orders set stock_restored = true where id = p_order;
end $$;

-- Replace the old 3-argument version with the new one (history, new stages, cancellation requests).
drop function if exists public.set_order_status(text, text, uuid);

create or replace function public.set_order_status(
  p_order_number text, p_status text, p_user uuid default null,
  p_note text default null, p_actor uuid default null, p_actor_type text default 'admin'
) returns public.orders
language plpgsql security definer set search_path = public as $$
declare v_o public.orders; v_from text; v_allowed text[]; v_actor text;
begin
  if p_status not in ('pending','confirmed','processing','packed','shipped','out_for_delivery','delivered','cancellation_requested','cancelled') then
    raise exception 'INVALID_STATUS';
  end if;
  select * into v_o from public.orders where order_number = p_order_number for update;
  if not found then raise exception 'NOT_FOUND'; end if;
  v_from := v_o.order_status;

  if p_user is not null then
    -- Customer: may only ask to cancel their OWN order.
    if v_o.user_id is distinct from p_user then raise exception 'NOT_FOUND'; end if;
    if p_status <> 'cancelled' then raise exception 'NOT_ALLOWED'; end if;
    if v_from = 'pending' and v_o.payment_status <> 'paid' then
      v_actor := 'customer';                                   -- not paid and not confirmed yet: cancel immediately
    elsif v_from in ('pending', 'confirmed', 'processing', 'packed') then
      update public.orders set order_status = 'cancellation_requested', status_before_request = v_from,
             cancel_reason = p_note, cancel_requested_at = now(), updated_at = now()
      where id = v_o.id returning * into v_o;
      insert into public.order_events(order_id, event_type, from_status, to_status, note, actor, actor_id)
      values (v_o.id, 'cancellation_requested', v_from, 'cancellation_requested', p_note, 'customer', p_user);
      return v_o;
    else
      raise exception 'NOT_ALLOWED';
    end if;
  else
    v_actor := coalesce(p_actor_type, 'admin');
    if p_status = v_from then return v_o; end if;
    v_allowed := case v_from
      when 'pending' then array['confirmed', 'cancelled']
      when 'confirmed' then array['processing', 'packed', 'cancelled']
      when 'processing' then array['packed', 'cancelled']
      when 'packed' then array['shipped', 'cancelled']
      when 'shipped' then array['out_for_delivery', 'delivered']
      when 'out_for_delivery' then array['delivered']
      when 'cancellation_requested' then array['cancelled', coalesce(v_o.status_before_request, 'confirmed')]
      else array[]::text[] end;
    if not (p_status = any (v_allowed)) then raise exception 'INVALID_TRANSITION:%:%', v_from, p_status; end if;
  end if;

  if p_status in ('confirmed','processing','packed','shipped','out_for_delivery','delivered')
     and v_o.payment_method = 'ONLINE' and v_o.payment_status <> 'paid' then
    raise exception 'PAYMENT_PENDING';
  end if;

  if p_status = 'cancelled' then
    perform public.restore_order_stock(v_o.id);
    update public.orders set order_status = 'cancelled', updated_at = now(), cancel_reason = coalesce(cancel_reason, p_note),
      payment_status = case when payment_status in ('pending', 'failed') and payment_method = 'ONLINE' then 'cancelled' else payment_status end,
      refund_status = case when payment_status = 'paid' then coalesce(refund_status, 'processing') else refund_status end
    where id = v_o.id returning * into v_o;
  else
    update public.orders set order_status = p_status, updated_at = now(),
      delivered_at = case when p_status = 'delivered' then now() else delivered_at end,
      payment_status = case when p_status = 'delivered' and payment_method = 'COD' and payment_status = 'pending' then 'paid' else payment_status end,
      paid_at = case when p_status = 'delivered' and payment_method = 'COD' and payment_status = 'pending' then now() else paid_at end
    where id = v_o.id returning * into v_o;
  end if;

  insert into public.order_events(order_id, event_type, from_status, to_status, note, actor, actor_id)
  values (v_o.id, 'status', v_from, p_status, p_note, v_actor, coalesce(p_actor, p_user));
  return v_o;
end $$;

-- Idempotent: called by /api/verify-payment and the Razorpay webhook.
create or replace function public.mark_order_paid(p_razorpay_order_id text, p_payment_id text, p_amount_paise bigint default null)
returns public.orders
language plpgsql security definer set search_path = public as $$
declare v_o public.orders;
begin
  select * into v_o from public.orders where razorpay_order_id = p_razorpay_order_id for update;
  if not found then raise exception 'NOT_FOUND'; end if;
  if p_amount_paise is not null and p_amount_paise <> round(v_o.total * 100) then raise exception 'AMOUNT_MISMATCH'; end if;
  if v_o.payment_status = 'paid' then return v_o; end if;
  update public.orders set
    payment_status = 'paid', razorpay_payment_id = p_payment_id, paid_at = now(), updated_at = now(),
    order_status = case when order_status = 'pending' then 'confirmed' else order_status end,
    admin_note = case when order_status = 'cancelled'
      then trim(coalesce(admin_note || ' | ', '') || 'PAID AFTER CANCELLATION - refund or reinstate manually')
      else admin_note end,
    refund_status = case when order_status = 'cancelled' then coalesce(refund_status, 'processing') else refund_status end
  where id = v_o.id returning * into v_o;
  insert into public.order_events(order_id, event_type, from_status, to_status, note, actor)
  values (v_o.id, 'payment', null, 'paid', 'Online payment confirmed by Razorpay', 'razorpay');
  return v_o;
end $$;

create or replace function public.expire_unpaid_orders(p_hours int default 24) returns int
language plpgsql security definer set search_path = public as $$
declare v record; n int := 0;
begin
  for v in select order_number from public.orders
           where payment_method = 'ONLINE' and payment_status in ('pending', 'failed')
             and order_status = 'pending' and created_at < now() - make_interval(hours => p_hours)
  loop
    perform public.set_order_status(v.order_number, 'cancelled', null, 'Unpaid online order expired', null, 'system');
    n := n + 1;
  end loop;
  return n;
end $$;

