-- ---------- Slugs + updated_at ----------
create or replace function public.set_product_defaults() returns trigger
language plpgsql as $$
begin
  if new.slug is null or new.slug = '' then
    new.slug := coalesce(nullif(trim(both '-' from left(regexp_replace(lower(new.name), '[^a-z0-9]+', '-', 'g'), 60)), ''), 'item')
                || '-' || new.id;
  end if;
  new.updated_at := now();
  return new;
end $$;

